package com.github.skobsrpsk.holomusic;

/**
 * Реализуют экраны, у которых строка поиска в action bar должна что-то
 * фильтровать. Каждый раздел ищет только по тому полю, что показано
 * крупным шрифтом в его собственных строках списка — не по всем полям
 * сразу и не по чужим (например, в разделе "Исполнители" ищем по имени
 * исполнителя, а не по названиям треков внутри).
 */
public interface Searchable {
    void filter(String query);
}
